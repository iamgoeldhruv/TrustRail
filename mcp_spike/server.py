
import json
import logging
import os
from typing import Any

import uvicorn
from mcp.server import MCPServer
from pydantic import BaseModel


logger = logging.getLogger("trustrail.mcp")

mcp = MCPServer("TrustRail-MCP-Spike")


SERVER_STATE: dict[str, str] = {
    "status": "running",
    "message": "Hello from TrustRail MCP Server",
}


# Fault injection is disabled by default.
DROP_AFTER_APPLY=True


class StatusResponse(BaseModel):
    status: str
    message: str


class UpdateStatusResponse(BaseModel):
    success: bool
    updated_message: str


@mcp.tool()
def get_status() -> StatusResponse:
    """Read the current server status."""

    return StatusResponse(
        status=SERVER_STATE["status"],
        message=SERVER_STATE["message"],
    )


@mcp.tool()
def update_status(message: str) -> UpdateStatusResponse:
    """Update the server status message."""

    normalized_message = message.strip()

    if not normalized_message:
        raise ValueError("Status message cannot be empty.")

    if len(normalized_message) > 200:
        raise ValueError("Status message cannot exceed 200 characters.")

    # Apply the operation first.
    SERVER_STATE["message"] = normalized_message

    logger.info(
        "Status successfully updated: %s",
        normalized_message,
    )

    return UpdateStatusResponse(
        success=True,
        updated_message=SERVER_STATE["message"],
    )


class DropAfterApplyMiddleware:
    """
    Deliberately interrupts the HTTP response after update_status
    has successfully executed.

    This simulates a lost response after the server applies a write.
    """

    def __init__(self, app: Any) -> None:
        self.app = app

    async def __call__(self, scope: dict, receive: Any, send: Any) -> None:

        # Only inspect HTTP POST requests to the MCP endpoint.
        if (
            scope["type"] != "http"
            or scope.get("method") != "POST"
            or scope.get("path") != "/mcp"
            or not DROP_AFTER_APPLY
        ):
            await self.app(scope, receive, send)
            return

        # Read and buffer the incoming request body.
        request_body = bytearray()

        while True:
            message = await receive()

            if message["type"] == "http.disconnect":
                return

            request_body.extend(message.get("body", b""))

            if not message.get("more_body", False):
                break

        # Check whether this request invokes update_status.
        try:
            request_data = json.loads(request_body)

            is_update_status = (
                isinstance(request_data, dict)
                and request_data.get("method") == "tools/call"
                and request_data.get("params", {}).get("name")
                == "update_status"
            )

        except (ValueError, AttributeError, TypeError):
            is_update_status = False

        if not is_update_status:
            # Replay the original request normally.
            await self.app(
                scope,
                self._replay_receive(request_body),
                send,
            )
            return

        # Collect the response generated by the MCP application.
        # At this point the tool has already executed.
        response_messages = []

        async def capture_send(message: dict) -> None:
            response_messages.append(message)

        await self.app(
            scope,
            self._replay_receive(request_body),
            capture_send,
        )

        response_start = next(
            (
                message
                for message in response_messages
                if message["type"] == "http.response.start"
            ),
            None,
        )

        response_body = b"".join(
            message.get("body", b"")
            for message in response_messages
            if message["type"] == "http.response.body"
        )

        if response_start is None or not response_body:
            logger.error(
                "Cannot inject response drop: no complete MCP response."
            )

            for message in response_messages:
                await send(message)

            return

        # Send response headers, then only part of the body.
        # The original Content-Length, if present, remains unchanged.
        await send(response_start)

        partial_body = response_body[: max(1, len(response_body) // 2)]

        await send(
            {
                "type": "http.response.body",
                "body": partial_body,
                "more_body": True,
            }
        )

        logger.warning(
            "FAULT INJECTION: update_status was applied, "
            "but its HTTP response is being interrupted."
        )

        # Raising after response headers and a partial body have been
        # sent causes the ASGI server to terminate the incomplete response.
        raise ConnectionError(
            "Simulated connection drop after applying update_status"
        )

    @staticmethod
    def _replay_receive(body: bytearray):
        sent = False

        async def receive() -> dict:
            nonlocal sent

            if not sent:
                sent = True

                return {
                    "type": "http.request",
                    "body": bytes(body),
                    "more_body": False,
                }

            return {
                "type": "http.disconnect",
            }

        return receive


def main() -> None:
    host = "0.0.0.0"
    port = int(os.environ.get("PORT", "8000"))

    # Build the Streamable HTTP ASGI application.
    mcp_app = mcp.streamable_http_app(json_response=True)

    # Wrap it with our fault-injection middleware.
    app = DropAfterApplyMiddleware(mcp_app)

    logger.info("Starting TrustRail MCP Spike")
    logger.info("Fault injection enabled: %s", DROP_AFTER_APPLY)

    uvicorn.run(
        app,
        host=host,
        port=port,
        log_level="info",
    )


if __name__ == "__main__":
    main()